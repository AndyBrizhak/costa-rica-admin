/**
 * Преобразует строку в URL-безопасный слаг.
 * Учитывает специфику испанских символов (акценты и ñ).
 */
export const slugify = (text: string): string => {
  return text
    .toString()
    .toLowerCase()
    .trim()
    .normalize("NFD") // Разделяет базовые буквы и их диакритические знаки (акценты)
    .replace(/[\u0300-\u036f]/g, "") // Удаляет диакритические знаки (акценты)
    .replace(/ñ/g, "n") // Дополнительная подстраховка для ñ
    .replace(/\s+/g, "-") // Заменяет пробелы на дефисы
    .replace(/[^\w-]+/g, "") // Удаляет все символы, кроме букв, цифр и дефисов
    .replace(/--+/g, "-") // Заменяет двойные дефисы на один
    .replace(/^-+/, "") // Удаляет дефисы в начале строки
    .replace(/-+$/, ""); // Удаляет дефисы в конце строки
};
